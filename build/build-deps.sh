#!/bin/bash -e
# Cross-build riscos-gtk's dependency stack for RISC OS into $STAGE (static);
# with TARGET=linuxarm, the same for the QEMU tests (see env.sh).
# Adapted from riscos-warzone2100 build/build-deps.sh (GPL version 2 or later; see LICENCES.md).
# Sources come from $DL (build/fetch-sources.sh); each library is unpacked
# fresh into $SRC, patched from patches/, built and installed. A library
# already in $STAGE/lib is skipped, so a failed run can be resumed
# (delete its .a to rebuild it).
#
# Built: zlib, libffi, PCRE2, a minimal libintl (riscos/intl), GLib; libpng,
# libjpeg-turbo, FreeType, expat, fontconfig; fribidi, harfbuzz, pixman,
# cairo, pango, gdk-pixbuf, ATK, libepoxy.
. "$(dirname "$0")/env.sh"
cd "$SRC"
HOSTARGS="--host=$HOST --prefix=$PREFIX --disable-shared --enable-static"
# autotools: make install DESTDIR=$SYSROOT, then drop the .la files (they
# name $PREFIX paths, which only exist inside SYSROOT).
inst() { make "$@" DESTDIR="$SYSROOT"; rm -f "$STAGE"/lib/*.la; }
step() { echo; echo "=== $*"; }
have() { [ -f "$STAGE/lib/$1" ] && echo "    (already built)"; }
# set -e doesn't see failures inside "if" conditions or before "&&", so each
# step ends by checking that its library is there.
need() { [ -f "$STAGE/lib/$1" ] || { echo "build-deps.sh: $1 was not built (see the log in $SRC)" >&2; exit 1; }; }
fresh() {  # tarball dir: unpack a clean copy
  rm -rf "$2"; tar xf "$DL/$1"
}

# Compiler wrappers, used by meson, CMake and autotools alike:
# - GCCSDK's driver rejects -pthread (UnixLib has POSIX threads in its C
#   library), and meson adds it for dependency('threads'): drop it.
# - RISC OS links must be static: without -static, GCC links against the
#   toolchain's shared libunixlib (or, with that removed by
#   unixlib-overlay.sh, ld crashes). libtool swallows a -static in LDFLAGS,
#   so the wrapper adds it to every link (no -c/-S/-E).
mkdir -p "$SRC/.wrap"
static=; [ "$TARGET" = riscos ] && static=1
for t in gcc g++; do
  cat > "$SRC/.wrap/$HOST-$t" <<EOF
#!/bin/sh
# Generated by riscos-gtk build/build-deps.sh: drop -pthread; static links.
link=$static
for a; do
  shift
  case "\$a" in -pthread) continue;; -c|-S|-E) link=;; esac
  set -- "\$@" "\$a"
done
[ -n "\$link" ] && set -- -static "\$@"
exec "$TCBIN/$HOST-$t" "\$@"
EOF
  chmod +x "$SRC/.wrap/$HOST-$t"
done
export CC="$SRC/.wrap/$HOST-gcc" CXX="$SRC/.wrap/$HOST-g++"

# meson cross file ($HOST). host_machine.system 'riscos'
# is unknown to meson (it warns) and to the projects, which treat it as a
# generic Unix.
args=$(printf "'%s', " $RO_CFLAGS "-I$STAGE/include")
cat > "$STAGE/meson-cross.txt" <<EOF
[binaries]
c = '$SRC/.wrap/$HOST-gcc'
cpp = '$SRC/.wrap/$HOST-g++'
ar = '$TCBIN/$HOST-ar'
strip = '$TCBIN/$HOST-strip'
pkg-config = 'pkg-config'
# GLib's build tools from the build machine (Ubuntu's libglib2.0-dev-bin,
# also 2.80): the ones in the sysroot are RISC OS programs.
glib-compile-resources = '/usr/bin/glib-compile-resources'
glib-compile-schemas = '/usr/bin/glib-compile-schemas'
glib-mkenums = '/usr/bin/glib-mkenums'
glib-genmarshal = '/usr/bin/glib-genmarshal'
gdbus-codegen = '/usr/bin/gdbus-codegen'

[properties]
pkg_config_libdir = '$STAGE/lib/pkgconfig:$STAGE/share/pkgconfig'
sys_root = '$SYSROOT'
needs_exe_wrapper = true

[built-in options]
c_args = [${args%, }]
cpp_args = [${args%, }]
c_link_args = ['-L$STAGE/lib']
cpp_link_args = ['-L$STAGE/lib']
default_library = 'static'
# pkg-config --static, so the private dependencies of static libraries link.
prefer_static = true
prefix = '$PREFIX'

[host_machine]
system = '$MESON_SYSTEM'
cpu_family = 'arm'
cpu = 'cortex-a8'
endian = 'little'
EOF
# meson must not see the autoconf-style variables from env.sh.
meson_env() { env -u CC -u CXX -u AR -u RANLIB -u STRIP -u CFLAGS -u CXXFLAGS -u CPPFLAGS -u LDFLAGS "$@"; }
# Our .pc files must not pass -pthread on either (some build systems don't
# go through the wrapper).
fix_pc() { sed -i 's/ -pthread//g' "$STAGE"/lib/pkgconfig/*.pc; }

step "zlib 1.3.1"
if ! have libz.a; then
fresh zlib_1.3.dfsg+really1.3.1.orig.tar.gz zlib-1.3.1; cd zlib-1.3.1
CHOST=$HOST ./configure --static --prefix="$PREFIX" > ../zlib.log
make -j$JOBS libz.a >> ../zlib.log
inst install >> ../zlib.log; cd ..
fi
need libz.a

step "libffi 3.4.6 (GObject's generic marshaller)"
if ! have libffi.a; then
fresh libffi_3.4.6.orig.tar.gz libffi-3.4.6; cd libffi-3.4.6
# The orig tarball is a git export without configure.
autoreconf -fi > ../ffi.log 2>&1; fresh_config_sub .
./configure $HOSTARGS --disable-docs --disable-multi-os-directory >> ../ffi.log
make -j$JOBS >> ../ffi.log 2>&1
inst install >> ../ffi.log; cd ..
fi
need libffi.a

step "PCRE2 10.42 (GRegex; 8-bit library only, no JIT)"
if ! have libpcre2-8.a; then
fresh pcre2_10.42.orig.tar.gz pcre2-10.42; cd pcre2-10.42; fresh_config_sub .
./configure $HOSTARGS --disable-jit --enable-unicode > ../pcre2.log
make -j$JOBS libpcre2-8.la >> ../pcre2.log
inst install-libLTLIBRARIES install-includeHEADERS install-nodist_includeHEADERS \
  install-pkgconfigDATA >> ../pcre2.log; cd ..
fi
need libpcre2-8.a

if [ "$TARGET" = riscos ]; then   # glibc has these
step "libintl (riscos/intl: no catalogues, English only)"
if ! have libintl.a; then
mkdir -p "$STAGE/lib" "$STAGE/include"
$CC $RO_CFLAGS -c "$REPO_DIR/riscos/intl/intl.c" -o intl.o
$AR rcs "$STAGE/lib/libintl.a" intl.o
cp "$REPO_DIR/riscos/intl/libintl.h" "$STAGE/include/"
fi
need libintl.a
fi

step "GLib 2.80.0 (patches/glib-2.80.0-riscos.diff)"
if ! have libglib-2.0.a; then
fresh glib2.0_2.80.0.orig.tar.xz glib-2.80.0
patch -d glib-2.80.0 -p1 -s < "$REPO_DIR/patches/glib-2.80.0-riscos.diff"
cd glib-2.80.0
# prefer_static=false: with it, meson's "system" lookup of libintl.a (ours,
# in $STAGE/lib) fails; GLib's own dependencies have no private libraries.
meson_env meson setup _build --cross-file "$STAGE/meson-cross.txt" $GLIB_MESON_OPTS \
  -Dlibmount=disabled -Dprefer_static=false > ../glib.log
meson_env ninja -C _build >> ../glib.log
meson_env meson install -C _build --destdir "$SYSROOT" >> ../glib.log
cd ..
fi
need libglib-2.0.a
fix_pc

# ---- the font stack (recipes from riscos-warzone2100's build-deps.sh) ----

# CMake toolchain file (as riscos-warzone2100's build/riscos.cmake).
cat > "$STAGE/riscos.cmake" <<EOF2
SET(CMAKE_SYSTEM_NAME $CMAKE_SYSTEM)   # GNU for RISC OS, as GCCSDK's own toolchain file: makes UNIX true
SET(CMAKE_SYSTEM_VERSION 1)
SET(CMAKE_SYSTEM_PROCESSOR arm)
SET(CMAKE_C_COMPILER   $SRC/.wrap/$HOST-gcc)
SET(CMAKE_CXX_COMPILER $SRC/.wrap/$HOST-g++)
SET(CMAKE_FIND_ROOT_PATH $STAGE $GCCSDK_ENV)
SET(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
SET(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
SET(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
SET(BUILD_SHARED_LIBS OFF)
EOF2

step "libpng 1.6.37"
if ! have libpng16.a; then
fresh libpng1.6_1.6.37.orig.tar.gz libpng-1.6.37; cd libpng-1.6.37; fresh_config_sub .
./configure $HOSTARGS --disable-arm-neon > ../libpng.log
make -j$JOBS >> ../libpng.log
inst install >> ../libpng.log; cd ..
fi
need libpng16.a

step "libjpeg-turbo 2.1.5 (CMake; for gdk-pixbuf)"
if ! have libjpeg.a; then
fresh libjpeg-turbo_2.1.5.orig.tar.gz libjpeg-turbo-2.1.5
rm -rf jpeg-build; mkdir jpeg-build; cd jpeg-build
# No SIMD: its ARM NEON code is untested on RISC OS (alignment); C only.
cmake ../libjpeg-turbo-2.1.5 -DCMAKE_TOOLCHAIN_FILE="$STAGE/riscos.cmake" \
  -DCMAKE_INSTALL_PREFIX="$PREFIX" -DENABLE_SHARED=OFF -DENABLE_STATIC=ON \
  -DWITH_SIMD=OFF -DWITH_TURBOJPEG=OFF -DCMAKE_BUILD_TYPE=Release \
  -DCMAKE_C_FLAGS="$RO_CFLAGS" > ../jpeg.log
make -j$JOBS >> ../jpeg.log
make install DESTDIR="$SYSROOT" >> ../jpeg.log; cd ..
fi
need libjpeg.a

step "FreeType 2.10.1"
if ! have libfreetype.a; then
fresh freetype_2.10.1.orig.tar.gz freetype-2.10.1; cd freetype-2.10.1; fresh_config_sub .
./configure $HOSTARGS --with-zlib=yes --with-png=yes --with-bzip2=no \
  --with-harfbuzz=no --with-brotli=no > ../freetype.log
make -j$JOBS >> ../freetype.log
inst install >> ../freetype.log; cd ..
fi
need libfreetype.a

step "expat 2.2.9 (CMake)"
if ! have libexpat.a; then
fresh expat_2.2.9.orig.tar.gz libexpat-R_2_2_9
rm -rf expat-build; mkdir expat-build; cd expat-build
cmake ../libexpat-R_2_2_9/expat -DCMAKE_TOOLCHAIN_FILE="$STAGE/riscos.cmake" \
  -DCMAKE_INSTALL_PREFIX="$PREFIX" -DEXPAT_SHARED_LIBS=OFF \
  -DEXPAT_BUILD_TOOLS=OFF -DEXPAT_BUILD_EXAMPLES=OFF -DEXPAT_BUILD_TESTS=OFF \
  -DEXPAT_BUILD_DOCS=OFF -DCMAKE_BUILD_TYPE=Release -DCMAKE_C_FLAGS="$RO_CFLAGS" > ../expat.log
make -j$JOBS >> ../expat.log
make install DESTDIR="$SYSROOT" >> ../expat.log; cd ..
fi
need libexpat.a

step "fontconfig 2.14.1 (patches/fontconfig-2.14.1-riscos.diff)"
# PackMan's version, so programs read the same fonts.conf and cache format
# (cache-8) as other fontconfig programs (as riscos-warzone2100).
if ! have libfontconfig.a; then
fresh fontconfig_2.14.1.orig.tar.xz fontconfig-2.14.1
patch -d fontconfig-2.14.1 -p1 -s < "$REPO_DIR/patches/fontconfig-2.14.1-riscos.diff"
cd fontconfig-2.14.1; fresh_config_sub .
./configure $HOSTARGS --disable-docs --disable-nls --disable-cache-build \
  --sysconfdir=/FontConfig --localstatedir=/FontConfig/var \
  --with-default-fonts=/GTK/fonts > ../fontconfig.log
make -j$JOBS -C src >> ../fontconfig.log
inst -C src install >> ../fontconfig.log
inst -C fontconfig install >> ../fontconfig.log
install -m644 fontconfig.pc "$STAGE/lib/pkgconfig/"; cd ..
fi
need libfontconfig.a
fix_pc

# ---- the rest of GTK 3's dependencies (meson) ----
# mesonlib TARBALL DIR LIBRARY [meson options...]: unpack DIR fresh, apply
# patches/DIR-riscos.diff if there is one, build and install; skipped if
# $STAGE/lib/LIBRARY exists.
mesonlib() {
  local tb=$1 d=$2 lib=$3; shift 3
  step "$d"
  if ! have "$lib"; then
    fresh "$tb" "$d"
    [ -f "$REPO_DIR/patches/$d-riscos.diff" ] && patch -d "$d" -p1 -s < "$REPO_DIR/patches/$d-riscos.diff"
    ( cd "$d"
      meson_env meson setup _build --cross-file "$STAGE/meson-cross.txt" \
        --wrap-mode=nofallback "$@" > "../$d.log"
      meson_env ninja -C _build >> "../$d.log"
      meson_env meson install -C _build --destdir "$SYSROOT" >> "../$d.log" )
    fix_pc
  fi
  need "$lib"
}

if [ "$TARGET" = riscos ]; then   # glibc has these
step "libdl (riscos/dl: dlopen always fails; for libepoxy)"
# Built after GLib on purpose: GLib's gmodule stays without dlopen.
if ! have libdl.a; then
$CC $RO_CFLAGS -c "$REPO_DIR/riscos/dl/dl.c" -o dl.o
$AR rcs "$STAGE/lib/libdl.a" dl.o
fi
need libdl.a
fi

mesonlib fribidi_1.0.13.orig.tar.xz fribidi-1.0.13 libfribidi.a \
  -Ddocs=false -Dbin=false -Dtests=false

# harfbuzz with FreeType and GLib; no cairo (that comes after), ICU or
# graphite.
mesonlib harfbuzz_8.3.0.orig.tar.xz harfbuzz-8.3.0 libharfbuzz.a \
  -Dglib=enabled -Dgobject=disabled -Dcairo=disabled -Dchafa=disabled \
  -Dicu=disabled -Dgraphite=disabled -Dgraphite2=disabled -Dfreetype=enabled \
  -Dtests=disabled -Dintrospection=disabled -Ddocs=disabled -Dutilities=disabled \
  -Dbenchmark=disabled

# pixman: plain C for now. Its ARM SIMD/NEON code is chosen at run time,
# and pixman-arm.c has no RISC OS CPU detection (it would pick none), so it
# isn't built. Worth adding later for speed (every RISC OS 5 machine is
# ARMv7; the Pi has NEON).
mesonlib pixman_0.42.2.orig.tar.gz pixman-0.42.2 libpixman-1.a \
  -Dloongson-mmi=disabled -Dmmx=disabled -Dsse2=disabled -Dssse3=disabled \
  -Dvmx=disabled -Darm-simd=disabled -Dneon=disabled -Da64-neon=disabled \
  -Diwmmxt=disabled -Dmips-dspr2=disabled -Dopenmp=disabled -Dgtk=disabled \
  -Dlibpng=disabled -Dtests=disabled

# cairo: image surfaces, PNG, FreeType/fontconfig fonts. No X11.
mesonlib cairo_1.18.0.orig.tar.xz cairo-1.18.0 libcairo.a \
  -Ddwrite=disabled -Dfontconfig=enabled -Dfreetype=enabled -Dpng=enabled \
  -Dquartz=disabled -Dtee=disabled -Dxcb=disabled -Dxlib=disabled \
  -Dxlib-xcb=disabled -Dzlib=enabled -Dtests=disabled -Dgtk2-utils=disabled \
  -Dglib=enabled -Dspectre=disabled -Dsymbol-lookup=disabled -Dgtk_doc=false

mesonlib pango1.0_1.52.1+ds.orig.tar.xz pango-1.52.1 libpango-1.0.a \
  -Dgtk_doc=false -Dintrospection=disabled -Dinstall-tests=false \
  -Dfontconfig=enabled -Dsysprof=disabled -Dlibthai=disabled -Dcairo=enabled \
  -Dxft=disabled -Dfreetype=enabled

# gdk-pixbuf: every loader (PNG, JPEG, GIF, BMP, ICO, XPM...) built into the library (no module
# loading without dlopen); content sniffing by file name only (no
# shared-mime-info database yet).
mesonlib gdk-pixbuf_2.42.10+dfsg.orig.tar.xz gdk-pixbuf-2.42.10 libgdk_pixbuf-2.0.a \
  -Dpng=enabled -Djpeg=enabled -Dtiff=disabled -Dbuiltin_loaders=all \
  -Dgtk_doc=false -Ddocs=false -Dintrospection=disabled -Dman=false \
  -Drelocatable=false -Dtests=false -Dinstalled_tests=false -Dgio_sniffing=false

mesonlib atk1.0_2.36.0.orig.tar.xz atk-2.36.0 libatk-1.0.a \
  -Ddocs=false -Dintrospection=false

# libepoxy: a build dependency of GTK; without GLX/EGL nothing in it is
# used until GtkGLArea gets a backend (riscos-mesa EGL, later).
mesonlib libepoxy_1.5.10.orig.tar.gz libepoxy-1.5.10 libepoxy.a \
  -Ddocs=false -Dglx=no -Degl=no -Dx11=false -Dtests=false

# ---- GTK itself, with the RISC OS GDK backend (M2) ----
step "GTK 3.24.41 (patches/gtk+3.0-3.24.41-riscos.diff + gdk/riscos)"
if ! have libgtk-3.a; then
fresh gtk+3.0_3.24.41.orig.tar.xz gtk+-3.24.41
patch -d gtk+-3.24.41 -p1 -s < "$REPO_DIR/patches/gtk+3.0-3.24.41-riscos.diff"
cp -r "$REPO_DIR/gdk/riscos" gtk+-3.24.41/gdk/riscos
# The QEMU test build: the backend's SWI calls go to the fake RISC OS
# (tests/fake/mesa-egl), whose kernel.h and swis.h stand in for UnixLib's.
# The fake itself goes into libgdk there, so that GTK's own tools and the
# tests link.
if [ "$TARGET" = linuxarm ]; then
  F=$REPO_DIR/tests/fake/mesa-egl
  cp "$F"/fake/kernel.h "$F"/fake/swis.h "$F"/fake_riscos.h "$STAGE/include/"
  cp "$F"/fake_riscos.c "$F"/fake_riscos.h gtk+-3.24.41/gdk/riscos/
  sed -i "s/  'gdkriscos-server.c',/  'gdkriscos-server.c',\n  'fake_riscos.c',/" gtk+-3.24.41/gdk/riscos/meson.build
fi
( cd gtk+-3.24.41
  # Nothing can be loaded without dlopen: no print backends, and the input
  # methods (IM modules) are all built into libgtk.
  meson_env meson setup _build --cross-file "$STAGE/meson-cross.txt" --wrap-mode=nofallback \
    -Dx11_backend=false -Dwayland_backend=false -Dbroadway_backend=false \
    -Dwin32_backend=false -Dquartz_backend=false -Driscos_backend=true \
    -Dxinerama=no -Dcloudproviders=false -Dprofiler=false -Dtracker3=false \
    -Dprint_backends= -Dcolord=no -Dgtk_doc=false -Dman=false \
    -Dintrospection=false -Ddemos=false -Dexamples=false -Dtests=false \
    -Dinstalled_tests=false -Dbuiltin_immodules=all > ../gtk.log
  meson_env ninja -C _build >> ../gtk.log
  meson_env meson install -C _build --destdir "$SYSROOT" >> ../gtk.log )
fix_pc
fi
need libgtk-3.a

step "done: $(ls "$STAGE"/lib/*.a | wc -l) static libraries in $STAGE/lib"
