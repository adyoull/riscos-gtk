#!/bin/sh
# mkgtkschemas.sh GTK_SOURCE_DIR > gdk/riscos/gdkschemas-riscos.h
# GTK 3's own GSettings schemas (gtk/org.gtk.Settings.*.gschema.xml),
# compiled with the host's glib-compile-schemas (the same GLib version as
# the build, 2.80), as a C array: riscos-gtk puts them on disk for a
# program that ships none (gdk/riscos/gdkschemas-riscos.c). The compiled
# format is little-endian GVariant, the same on the host and on RISC OS.
# MIT licence.
set -e
G=${1:?usage: $0 GTK_SOURCE_DIR}
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
cp "$G"/gtk/org.gtk.Settings.*.gschema.xml "$T/"
glib-compile-schemas --strict --targetdir="$T" "$T"
echo "/* gdkschemas-riscos.h - generated by tools/mkgtkschemas.sh from GTK"
echo "   $(basename "$G")'s gtk/org.gtk.Settings.*.gschema.xml (LGPL-2.1-or-later,"
echo "   as GTK), compiled by glib-compile-schemas $(glib-compile-schemas --version). Don't edit. */"
echo "static const unsigned char riscos_gtk_schemas[] = {"
od -An -v -tx1 "$T/gschemas.compiled" | sed 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/  /'
echo "};"
